// Regenerates INDEX.md: every lesson, grouped by track, plus a tag index and roadmap.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT, curriculum, lessons, loadReviews, pad, repoSlug } from './common.mjs';

const cur = curriculum();
const all = lessons();
const slug = repoSlug();
const video = (n) => (slug ? `https://github.com/${slug}/releases/tag/lesson-${pad(n)}` : `#`);
const notes = (l) => `${l.dir}/notes.md`;
const quizzed = new Set(loadReviews().sessions.map((s) => s.lesson));
const order = Object.keys(cur.tracks);

const out = [];
out.push('# Night School: lesson index', '');
out.push('_Auto-generated by `npm run index`. Do not edit by hand._', '');
const latest = all.at(-1);
if (latest) {
  out.push(`**Latest:** #${latest.number} · [${latest.title}](${notes(latest)}) · [▶ video](${video(latest.number)}) · ${latest.date}`, '');
}
out.push('| Track | Done | Remaining |', '|---|---|---|');
for (const t of order) {
  const n = all.filter((l) => l.track === t).length;
  out.push(`| ${cur.tracks[t].label} | ${n} | ${cur.tracks[t].lessons.length - n} |`);
}
out.push('');

for (const t of order) {
  const ls = all.filter((l) => l.track === t);
  out.push(`## ${cur.tracks[t].label}`, '');
  if (!ls.length) {
    out.push('_No lessons yet._', '');
    continue;
  }
  out.push('| # | Date | Lesson | Tags | Video | Quizzed |', '|---|---|---|---|---|---|');
  for (const l of ls) {
    out.push(
      `| ${l.number} | ${l.date} | [${l.title}](${notes(l)}) | ${l.tags.map((x) => `\`${x}\``).join(' ')} | [▶](${video(l.number)}) | ${quizzed.has(l.number) ? '✅' : '·'} |`,
    );
  }
  out.push('');
}

out.push('## By tag', '');
const tags = {};
for (const l of all) for (const t of l.tags) (tags[t] ??= []).push(l);
for (const t of Object.keys(tags).sort()) {
  out.push(`- **${t}**: ${tags[t].map((l) => `[#${l.number} ${l.title}](${notes(l)})`).join(', ')}`);
}
out.push('');

out.push('## Coming up', '');
const used = new Set(all.map((l) => l.curriculumId));
for (const t of order) {
  const next = cur.tracks[t].lessons.filter((l) => !used.has(l.id)).slice(0, 3);
  out.push(`- **${cur.tracks[t].label}**: ${next.map((l) => l.title).join(' → ') || '_track complete: will be extended_'}`);
}
out.push('');

writeFileSync(path.join(ROOT, 'INDEX.md'), out.join('\n'));
console.log(`INDEX.md: ${all.length} lesson(s)`);
